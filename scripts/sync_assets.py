#!/usr/bin/env python3
"""Regenerate src/shared/Assets.luau from assets/manifest.json.

Run after uploading assets (scripts/upload_assets.py fills the robloxAssetId fields in):

    python scripts/sync_assets.py

The manifest is the single source of truth for which file maps to which Luau key.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "assets" / "manifest.json"
OUT = ROOT / "src" / "shared" / "Assets.luau"

HEADER = """--!strict
-- Roblox asset ids for everything generated under /assets.
--
-- THIS FILE IS GENERATED by scripts/sync_assets.py from assets/manifest.json.
-- Edit the manifest (or run scripts/upload_assets.py, which fills the ids in),
-- then re-run `python scripts/sync_assets.py` to regenerate it.
--
-- An id of 0 means "not uploaded yet"; the game falls back to built-in sounds / parts.

local Assets = {
"""

FOOTER = """}

function Assets.soundId(key: string): string?
	local id = Assets.Sounds[key]
	if id and id ~= 0 then
		return "rbxassetid://" .. tostring(id)
	end
	return nil
end

function Assets.imageId(key: string): string?
	local id = Assets.Images[key]
	if typeof(id) == "number" and id ~= 0 then
		return "rbxassetid://" .. tostring(id)
	end
	return nil
end

function Assets.itemIcon(itemId: string): string?
	local id = Assets.Images.Items[itemId]
	if id and id ~= 0 then
		return "rbxassetid://" .. tostring(id)
	end
	return nil
end

function Assets.meshId(itemId: string): string?
	local id = Assets.Meshes[itemId]
	if id and id ~= 0 then
		return "rbxassetid://" .. tostring(id)
	end
	return nil
end

return Assets
"""


def luau_key(key: str) -> str:
    return key if key.isidentifier() else f'["{key}"]'


def main() -> int:
    manifest = json.loads(MANIFEST.read_text())
    sounds: dict[str, int] = {}
    images: dict[str, int] = {}
    item_icons: dict[str, int] = {}
    meshes: dict[str, int] = {}

    for entry in manifest["assets"]:
        aid = int(entry.get("robloxAssetId") or 0)
        kind, key = entry["kind"], entry["key"]
        if kind == "audio":
            sounds[key] = aid
        elif kind == "image":
            images[key] = aid
        elif kind == "itemIcon":
            item_icons[key] = aid
        elif kind == "mesh":
            meshes[key] = aid
            for alias in entry.get("aliases", []):
                meshes[alias] = aid
        else:
            print(f"unknown kind {kind!r} for {key}", file=sys.stderr)
            return 1

    lines = [HEADER, "\tSounds = {\n"]
    for k in sorted(sounds):
        lines.append(f"\t\t{luau_key(k)} = {sounds[k]},\n")
    lines.append("\t},\n\tImages = {\n")
    for k in sorted(images):
        lines.append(f"\t\t{luau_key(k)} = {images[k]},\n")
    lines.append("\t\tItems = {\n")
    for k in sorted(item_icons):
        lines.append(f"\t\t\t{luau_key(k)} = {item_icons[k]},\n")
    lines.append("\t\t} :: { [string]: number }, -- keyed by collectible Id\n\t},\n\tMeshes = {\n")
    for k in sorted(meshes):
        lines.append(f"\t\t{luau_key(k)} = {meshes[k]},\n")
    lines.append("\t} :: { [string]: number }, -- keyed by collectible Id\n")
    lines.append(FOOTER)

    OUT.write_text("".join(lines))
    uploaded = sum(1 for e in manifest["assets"] if e.get("robloxAssetId"))
    print(f"wrote {OUT.relative_to(ROOT)} ({uploaded}/{len(manifest['assets'])} assets have ids)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
